"""
BPE Tokenizer in the style of GPT-4: train with rustbpe, inference with tiktoken.

Also home to the cycled-RoPE position scheme (PositionTracker and friends), which lives
here because it is a property of how a conversation is *rendered* into tokens, and is
computed on CPU at tokenization time rather than inside the training loop.
"""

import os
import copy
from functools import lru_cache

SPECIAL_TOKENS = [
    # every document begins with the Beginning of Sequence (BOS) token that delimits documents
    "<|bos|>",
    # tokens below are only used during finetuning to render Conversations into token ids
    "<|user_start|>", # user messages
    "<|user_end|>",
    "<|assistant_start|>", # assistant messages
    "<|assistant_end|>",
    "<|python_start|>", # assistant invokes python REPL tool
    "<|python_end|>",
    "<|output_start|>", # python REPL outputs back to assistant
    "<|output_end|>",
]

# NOTE: this split pattern deviates from GPT-4 in that we use \p{N}{1,2} instead of \p{N}{1,3}
# I did this because I didn't want to "waste" too many tokens on numbers for smaller vocab sizes.
# I verified that 2 is the sweet spot for vocab size of 32K. 1 is a bit worse, 3 was worse still.
SPLIT_PATTERN = r"""'(?i:[sdmt]|ll|ve|re)|[^\r\n\p{L}\p{N}]?+\p{L}+|\p{N}{1,2}| ?[^\s\p{L}\p{N}]++[\r\n]*|\s*[\r\n]|\s+(?!\S)|\s+"""

# -----------------------------------------------------------------------------
# Cycled RoPE: message-strided virtual positions
#
# The idea: a message's positional encoding should not depend on how long the messages
# before it were. So at every message boundary we jump the virtual position to the next
# multiple of `message_stride`, with a parity that encodes *who is speaking*:
#
#   even multiples (2k * M)     <- fed to the model:      BOS, user turns, tool output
#   odd multiples ((2k+1) * M)  <- generated by the model: assistant turns, tool code
#
# Within a message, positions increment contiguously, so the base model's local position
# semantics are untouched; only the offsets between messages change.
#
#   BOS  user_start  "hi"  user_end  |  asst_start  "hello"  asst_end  |  user_start  "ok"
#   pos:  0    1       2      3      |     512        513       514    |     1024      1025
#         <---------- even (0*M) --->  <------- odd (1*M) ----------->  <-- even (2*M) -->
#
# Note BOS does not get a slot of its own: it is already in an even slot and the user turn
# that follows wants the same parity, so it simply continues contiguously.

USER_PARITY = 0      # even multiples of the stride
ASSISTANT_PARITY = 1 # odd multiples of the stride


def conversation_boundaries(tokenizer):
    """
    Build the two boundary maps used by PositionTracker for nanochat's chat format.

    align_at:    token id -> parity. This token *starts* a new segment, so it is the first
                 token placed at the newly aligned position.
    align_after: token id -> parity. The token *following* this one starts a new segment.
                 Used for <|output_end|>: the tool output owns its (even) slot right up to
                 its closing token, and whatever the assistant says next belongs to a fresh
                 odd slot.
    """
    special = tokenizer.encode_special
    align_at = {
        tokenizer.get_bos_token_id():   USER_PARITY,      # start of the document
        special("<|user_start|>"):      USER_PARITY,      # user turn
        special("<|output_start|>"):    USER_PARITY,      # python output, fed back to the model
        special("<|assistant_start|>"): ASSISTANT_PARITY, # assistant turn
        special("<|python_start|>"):    ASSISTANT_PARITY, # tool code, written by the assistant
    }
    align_after = {
        special("<|output_end|>"):      ASSISTANT_PARITY, # assistant resumes after tool output
    }
    return align_at, align_after


class PositionTracker:
    """
    Incremental cycled-RoPE position generator: feed it token ids one at a time (or in
    bulk) and it returns the virtual position of each. Incremental so that the same code
    drives both tokenization-time batching and token-by-token decoding in the Engine.

    With message_stride <= 0 this degenerates to plain contiguous positions, which keeps
    every caller free of "is the feature on?" branching.
    """

    def __init__(self, message_stride, align_at=None, align_after=None):
        self.message_stride = message_stride
        self.align_at = align_at or {}
        self.align_after = align_after or {}
        self.pos = 0            # position the next token will receive
        self.slot = 0           # index of the stride multiple the current segment started at
        self.pending = None     # parity requested by the previous token, applied to this one

    def clone(self):
        """Copy of the current state, e.g. to fan a prefilled prompt out to N decode rows."""
        other = PositionTracker(self.message_stride, self.align_at, self.align_after)
        other.pos, other.slot, other.pending = self.pos, self.slot, self.pending
        return other

    def _align(self, parity):
        """Move self.pos to the start of the next stride multiple with the given parity."""
        M = self.message_stride
        # Stay put if we are still inside the current segment's slot and it already has the
        # right parity. This is what lets BOS and the user turn that follows it share slot 0.
        if self.slot % 2 == parity and self.pos < (self.slot + 1) * M:
            return
        # Otherwise take the first slot with the right parity that lies at or after us. A
        # message that overflowed its slot therefore skips ahead rather than starting midway.
        m = -(-self.pos // M)  # ceil division: the first slot boundary at or after pos
        if m % 2 != parity:
            m += 1
        self.pos = m * M
        self.slot = m

    def step(self, token_id):
        """Return the virtual position of token_id and advance the state."""
        if self.message_stride > 0:
            parity = self.pending if self.pending is not None else self.align_at.get(token_id)
            self.pending = self.align_after.get(token_id)
            if parity is not None:
                self._align(parity)
        pos = self.pos
        self.pos += 1
        return pos

    def extend(self, token_ids):
        """Return the virtual positions of a whole run of tokens."""
        return [self.step(token_id) for token_id in token_ids]


def compute_conversation_position_ids(ids, message_stride, align_at=None, align_after=None):
    """
    Virtual positions for a rendered conversation, as a list of ints the same length as ids.

    ids:            list[int], a conversation rendered by render_conversation
    message_stride: int, 0 (or less) disables striding and yields contiguous positions
    align_at/after: boundary maps, see conversation_boundaries()
    """
    tracker = PositionTracker(message_stride, align_at, align_after)
    return tracker.extend(ids)


